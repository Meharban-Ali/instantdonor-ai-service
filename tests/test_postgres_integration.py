def test_postgres_donor_matching_query(pg_session):
    """Verify DonorRepository.find_nearby_donors on PostgreSQL 16."""
    # Insert test user
    pg_session.execute(text("""
        INSERT INTO users (id, name, email, password, phone, is_active, created_at)
        VALUES (101, 'Test Donor', 'donor@test.com', 'hashed_pass', '9876543210', true, NOW())
        ON CONFLICT (id) DO NOTHING;
    """))

    # Insert test donor profile in Delhi (lat 28.6139, lng 77.2090)
    pg_session.execute(text("""
        INSERT INTO donor_profiles (
            id, user_id, blood_group, city, state, latitude, longitude,
            is_available, reliability_score, response_rate, total_donations
        ) VALUES (
            201, 101, 'O+', 'Delhi', 'Delhi', 28.6139, 77.2090,
            true, 92.50, 95.00, 5
        ) ON CONFLICT (id) DO NOTHING;
    """))
    pg_session.commit()

    repo = DonorRepository(pg_session)
    donors = repo.find_nearby_donors(
        lat=28.6100,
        lng=77.2100,
        radius_km=15.0,
        blood_groups=["O+", "O-"],
        limit=10
    )

    assert len(donors) == 1
    assert donors[0]["id"] == 201
    assert donors[0]["blood_group"] == "O+"
    assert donors[0]["is_available"] is True


def test_postgres_demand_history_query_and_case(pg_session):
    """Verify BloodRequestRepository.get_request_history on PostgreSQL with city case-insensitivity."""
    # Insert sample requests
    pg_session.execute(text("""
        INSERT INTO users (id, name, email, password, phone, is_active, created_at)
        VALUES (102, 'Hospital User', 'hospital@test.com', 'hashed_pass', '9876543211', true, NOW())
        ON CONFLICT (id) DO NOTHING;
    """))

    # Insert blood requests with mixed case cities
    now = datetime.utcnow()
    pg_session.execute(text("""
        INSERT INTO blood_requests (
            id, blood_group, city, contact_phone, created_at, expired_at,
            hospital_name, patient_name, status, units_required, urgency, created_by
        ) VALUES
        (301, 'A+', 'Delhi', '9876543211', :c1, :e1, 'City Hospital', 'Patient 1', 'ACTIVE', 2, 'HIGH', 102),
        (302, 'A+', 'DELHI', '9876543211', :c2, :e2, 'Apollo Hospital', 'Patient 2', 'ACTIVE', 1, 'CRITICAL', 102),
        (303, 'B+', 'Mumbai', '9876543211', :c3, :e3, 'KEM Hospital', 'Patient 3', 'ACTIVE', 3, 'NORMAL', 102)
        ON CONFLICT (id) DO NOTHING;
    """), {
        "c1": now - timedelta(days=2), "e1": now + timedelta(days=2),
        "c2": now - timedelta(days=5), "e2": now + timedelta(days=1),
        "c3": now - timedelta(days=1), "e3": now + timedelta(days=3),
    })
    pg_session.commit()

    repo = BloodRequestRepository(pg_session)

    # Search with lowercase "delhi"
    delhi_lower = repo.get_request_history(city="delhi", blood_group="A+", days=30)
    assert len(delhi_lower) == 2, f"Expected 2 requests for 'delhi', got {len(delhi_lower)}"

    # Search with uppercase "DELHI"
    delhi_upper = repo.get_request_history(city="DELHI", blood_group="A+", days=30)
    assert len(delhi_upper) == 2, f"Expected 2 requests for 'DELHI', got {len(delhi_upper)}"

    # Check fields returned by PostgreSQL query
    item = delhi_lower[0]
    assert "days_ago" in item
    assert "weekday" in item
    assert item["blood_group"] == "A+"
    assert item["urgency"] in ("HIGH", "CRITICAL")

    # Verify SQL LIKE wildcard escaping (%, _, \)
    delhi_percent = repo.get_request_history(city="del%", blood_group="A+", days=30)
    assert len(delhi_percent) == 0, f"Expected 0 requests for unescaped wildcard 'del%', got {len(delhi_percent)}"

    delhi_underscore = repo.get_request_history(city="del_i", blood_group="A+", days=30)
    assert len(delhi_underscore) == 0, f"Expected 0 requests for unescaped wildcard 'del_i', got {len(delhi_underscore)}"

    delhi_backslash = repo.get_request_history(city="del\\hi", blood_group="A+", days=30)
    assert len(delhi_backslash) == 0, f"Expected 0 requests for 'del\\hi', got {len(delhi_backslash)}"


def test_escape_like_wildcards_unit():
    """Unit test for escape_like_wildcards utility function."""
    from utils.sql_utils import escape_like_wildcards
    assert escape_like_wildcards(None) is None
    assert escape_like_wildcards("") == ""
    assert escape_like_wildcards("Delhi") == "Delhi"
    assert escape_like_wildcards("100%") == "100\\%"
    assert escape_like_wildcards("New_York") == "New\\_York"
    assert escape_like_wildcards("Path\\City") == "Path\\\\City"
    assert escape_like_wildcards("%_\\") == "\\%\\_\\\\"
